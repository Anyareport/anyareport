import type { Report } from './api';
import { getStatusLabel } from './reportWorkflow';

interface IncidentSummaryOptions {
  generatedAt?: Date;
  generatedByName?: string | null;
  generatedByRole?: string | null;
  reporterName?: string | null;
  reporterPhone?: string | null;
}

function escapeHtml(value: string) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function formatDate(value: string | Date | null | undefined) {
  if (!value) return 'Not available';
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? 'Not available' : date.toLocaleString();
}

function field(label: string, value: string | null | undefined) {
  return `<div class="field"><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value?.trim() || 'Not available')}</dd></div>`;
}

export function createIncidentSummaryHtml(
  report: Report,
  {
    generatedAt = new Date(),
    generatedByName,
    generatedByRole,
    reporterName,
    reporterPhone,
  }: IncidentSummaryOptions = {}
) {
  const reference = report.referenceNumber || 'Reference not assigned';
  const category = report.subcategory
    ? `${report.category} · ${report.subcategory}`
    : report.category;
  const history = (report.statusHistory || [])
    .slice()
    .sort((left, right) => new Date(left.timestamp).getTime() - new Date(right.timestamp).getTime())
    .map(
      (entry) =>
        `<li><time>${escapeHtml(formatDate(entry.timestamp))}</time><span>${escapeHtml(getStatusLabel(entry.status))}</span>${entry.updatedBy ? `<span class="actor">Recorded by ${escapeHtml(entry.updatedBy)}</span>` : ''}</li>`
    )
    .join('');
  const responders = [
    report.acknowledgedByName,
    ...(report.backupRequests || []).flatMap((request) => request.joinedByNames || []),
  ].filter((name, index, names): name is string => Boolean(name) && names.indexOf(name) === index);
  const resolution = report.resolution;
  const hasResolution = report.status === 'resolved' || Boolean(resolution?.resolvedAt);
  const resolutionFields = hasResolution
    ? [
        field('Actions taken', resolution?.actionsTaken),
        field('Outcome', resolution?.outcome),
        ...(resolution?.verificationStatus === 'verified'
          ? [
              field('Verified by', resolution.verifiedByName || resolution.verifiedBy),
              field('Verified at', formatDate(resolution.verifiedAt)),
            ]
          : []),
      ].join('')
    : '';
  const reporterFields = reporterName
    ? [
        field('Reporter', reporterName),
        reporterPhone ? field('Reporter contact', reporterPhone) : '',
      ].join('')
    : '';
  const aiCategoryNote = report.aiSuggestedCategory
    ? report.aiSuggestedCategory.trim().toLocaleLowerCase() === report.category.trim().toLocaleLowerCase()
      ? 'Category assisted by AI.'
      : `AI suggested ${report.aiSuggestedCategory}; recorded category: ${report.category}.`
    : 'No AI category suggestion was recorded for this incident.';
  const generated = `Generated by ${generatedByName?.trim() || 'Unknown user'}${generatedByRole ? `, ${generatedByRole.replace(/\b\w/g, (letter) => letter.toUpperCase())}` : ''} on ${formatDate(generatedAt)}`;

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Incident Summary - ${escapeHtml(reference)}</title>
    <style>
      :root { color-scheme: light; font-family: Arial, Helvetica, sans-serif; color: #17212b; }
      * { box-sizing: border-box; }
      body { margin: 0; padding: 28px; font-size: 10.5pt; line-height: 1.4; }
      header { display: flex; justify-content: space-between; gap: 24px; align-items: flex-start; border-bottom: 2px solid #253b53; padding-bottom: 10px; margin-bottom: 12px; }
      h1 { font-size: 20pt; margin: 0 0 4px; }
      .brand { color: #526579; font-size: 9pt; font-weight: 700; letter-spacing: .08em; text-transform: uppercase; }
      .generated { color: #526579; font-size: 9pt; text-align: right; }
      h2 { font-size: 11.5pt; margin: 12px 0 6px; border-bottom: 1px solid #d5dde5; padding-bottom: 4px; }
      dl { display: grid; grid-template-columns: 1fr 1fr; gap: 6px 18px; margin: 0; }
      .field dt { color: #526579; font-size: 9pt; margin-bottom: 2px; }
      .field dd { margin: 0; overflow-wrap: anywhere; }
      .full { grid-column: 1 / -1; }
      .note { background: #f2f5f8; padding: 6px 9px; color: #394b5e; font-size: 8.5pt; margin-top: 8px; }
      .timeline { list-style: none; margin: 0; padding: 0; }
      .timeline li { display: grid; grid-template-columns: 150px 1fr; gap: 2px 12px; padding: 5px 0; border-bottom: 1px solid #e6ebf0; break-inside: avoid; }
      .timeline time, .actor { color: #526579; font-size: 9pt; }
      .actor { grid-column: 2; }
      .generated { max-width: 260px; }
      footer { border-top: 1px solid #d5dde5; padding-top: 7px; color: #526579; font-size: 8pt; break-inside: avoid; page-break-inside: avoid; }
      .print-button { border: 0; border-radius: 4px; padding: 9px 14px; margin-bottom: 18px; background: #245c93; color: white; font-size: 10pt; cursor: pointer; }
      @media print {
        @page { size: A4; margin: 0; }
        body { padding: 14mm; font-size: 9.5pt; }
        .print-button { display: none; }
        header { break-inside: avoid; }
      }
      @media screen {
        body { max-width: 900px; margin: 24px auto; box-shadow: 0 2px 18px #17212b22; }
      }
    </style>
  </head>
  <body>
    <button class="print-button" type="button" onclick="window.print()">Print / Save as PDF</button>
    <header>
      <div><div class="brand">Anyareport</div><h1>Incident Summary</h1><div>${escapeHtml(reference)}</div></div>
      <div class="generated">${escapeHtml(generated)}</div>
    </header>
    <main>
      <section>
        <h2>Incident details</h2>
        <dl>
          ${field('Reported', formatDate(report.createdAt))}
          ${field('Category', category)}
          ${field('Severity', report.severity)}
          ${field('Current status', getStatusLabel(report.status))}
          ${field('Location', report.location?.address)}
          ${reporterFields}
        </dl>
        <div class="note">${escapeHtml(aiCategoryNote)}</div>
      </section>
      <section>
        <h2>Description</h2>
        <div>${escapeHtml(report.description?.trim() || 'No description provided.').replace(/\r?\n/g, '<br>')}</div>
      </section>
      <section>
        <h2>Assigned responders</h2>
        <div>${responders.length ? responders.map(escapeHtml).join(', ') : 'No assigned responders recorded.'}</div>
      </section>
      <section>
        <h2>Status history</h2>
        ${history ? `<ol class="timeline">${history}</ol>` : '<div>No status history recorded.</div>'}
      </section>
      ${hasResolution ? `<section><h2>Resolution</h2><dl>${resolutionFields}</dl></section>` : ''}
    </main>
    <footer>Generated by Anyareport. Supplementary record; the physical blotter remains the official record.</footer>
  </body>
</html>`;
}
